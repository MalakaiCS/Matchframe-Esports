/** Writes docs/architecture/cloud-openapi.json and cloud-api-routes.md from the registered routes. Run: pnpm cloud:openapi */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CloudApp } from "../src/app.ts";
import { loadCloudConfig } from "../src/config.ts";
import { PgliteSql } from "../src/db/sql.ts";
import { buildRouter } from "../src/server.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const app = new CloudApp(loadCloudConfig({}), { sql: new PgliteSql() });
const router = buildRouter(app);
writeFileSync(join(root, "docs", "architecture", "cloud-openapi.json"), JSON.stringify(router.openapi({ title: "Matchframe cloud API", version: "0.1.0" }), null, 2) + "\n");
const lines = [
  "# Matchframe cloud API — route reference",
  "",
  "Generated by `pnpm cloud:openapi` from `services/cloud-api`. Website routes use the `mf_session` cookie (HttpOnly, SameSite=Lax) and refuse cross-origin browser mutations; desktop routes (`/v1/device/*`) use `Authorization: Bearer <device token>`. Request bodies are validated against `packages/cloud-contracts`. Full schemas: `cloud-openapi.json`.",
  "",
  "| Method | Path | Purpose |",
  "|---|---|---|",
  ...router.routeList().map((r) => `| ${r.method} | \`${r.path}\` | ${r.summary.replace(/\|/g, "\\|")} |`),
  "",
];
writeFileSync(join(root, "docs", "architecture", "cloud-api-routes.md"), lines.join("\n"));
console.log(`wrote ${router.routeList().length} routes`);
await app.close();
