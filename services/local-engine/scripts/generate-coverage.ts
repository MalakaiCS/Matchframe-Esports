/** Writes docs/maps/coverage.generated.md from the shipped map packs and utility profiles. Run: pnpm coverage:maps */
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { GRENADE_TYPES } from "@matchframe/contracts";
import { buildCoverageRow, REQUESTED_MAP_TARGETS } from "@matchframe/map-runtime";
import { Engine } from "../src/app.ts";
import { loadConfig } from "../src/config.ts";

process.env.MATCHFRAME_LOG_STDOUT = "0";
const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const engine = new Engine(
  loadConfig({
    dataDir: mkdtempSync(join(tmpdir(), "mf-coverage-")),
    captainUiDir: null,
    hudRendererDir: null,
    mapPackDir: join(root, "assets", "map-packs"),
    utilityProfilesFile: join(root, "assets", "utility-profiles", "measured.json"),
    workersDir: null,
    pythonPath: null,
  }),
);
const lines: string[] = [];
lines.push("<!-- Generated by `pnpm coverage:maps` from assets/map-packs and assets/utility-profiles. Do not edit by hand. -->", "");
lines.push("| Map | Pack | Regions (source) | Derived regions needing validation | Floor grid | Radar calibration | Cameras validated / unvalidated | Scenario rules |", "|---|---|---|---|---|---|---|---|");
const scenarioRules = engine.session.director.scenarioRules;
for (const t of REQUESTED_MAP_TARGETS) {
  const rt = engine.maps.get(t.mapName);
  const row = buildCoverageRow(t.mapName, rt, null);
  const derived = rt?.pack.regions.filter((r) => r.tags.includes("requires_operator_validation")).map((r) => r.id) ?? [];
  const rules = scenarioRules.filter((r) => r.mapName === t.mapName).map((r) => r.id);
  lines.push(
    `| ${t.displayName} (\`${t.mapName}\`) | ${row.mapPackPresent ? "yes" : "**no**"} | ${row.mapPackPresent ? `${row.regionCount} (${row.regionSource})` : "–"} | ${derived.join(", ") || "–"} | ${row.floorGrid ? "yes" : "no"} | ${row.radarCalibration} | ${row.validatedCameras} / ${row.unvalidatedCameras} | ${rules.join(", ") || "–"} |`,
  );
}
lines.push("", "### Utility profiles in use", "", "| Type | Source | Samples | Fuse (mean ± sd used live) | Effect duration (mean ± sd used live) |", "|---|---|---|---|---|");
const fmt = (d: { meanMs: number; sdMs: number } | null) => (d ? `${Math.round(d.meanMs)} ± ${Math.round(d.sdMs)} ms` : "–");
for (const type of GRENADE_TYPES) {
  const p = engine.utilityProfiles.profiles[type];
  lines.push(`| ${type} | ${p.source} | ${p.sampleCount} | ${fmt(p.fuse)} | ${fmt(p.effectDuration)} |`);
}
mkdirSync(join(root, "docs", "maps"), { recursive: true });
writeFileSync(join(root, "docs", "maps", "coverage.generated.md"), lines.join("\n") + "\n");
console.log("wrote docs/maps/coverage.generated.md");
await engine.shutdown();
process.exit(0);
