import { z } from "zod";

/**
 * Contracts between the Matchframe website/cloud API, its browser frontend and the desktop app.
 * Browser-safe: no Node imports here (token signing/verification lives in "./token").
 */

// ---------------------------------------------------------------------------- accounts & orgs

export const Email = z.string().trim().toLowerCase().email().max(254);
export const Password = z.string().min(10, "at least 10 characters").max(200);

export const SignupRequest = z.object({
  email: Email,
  password: Password,
  displayName: z.string().trim().min(1).max(80),
  orgName: z.string().trim().min(1).max(80),
});
export type SignupRequest = z.infer<typeof SignupRequest>;

export const LoginRequest = z.object({ email: Email, password: z.string().min(1).max(200) });

export const OrgRole = z.enum(["owner", "admin", "billing", "member"]);
export type OrgRole = z.infer<typeof OrgRole>;

/** Matchframe staff: support (help customers, verify emails, view organisations) or admin (everything, incl. staff roles, catalogue, credits). */
export const StaffRole = z.enum(["support", "admin"]);
export type StaffRole = z.infer<typeof StaffRole>;

export const UserView = z.object({
  id: z.string(),
  email: z.string(),
  displayName: z.string(),
  emailVerified: z.boolean(),
  /** True for any staff role. */
  staff: z.boolean(),
  staffRole: StaffRole.nullable().optional(),
  createdAt: z.string(),
});
export type UserView = z.infer<typeof UserView>;

export const OrgView = z.object({
  id: z.string(),
  name: z.string(),
  role: OrgRole,
  planId: z.string(),
  planName: z.string(),
  subscriptionStatus: z.string(),
});
export type OrgView = z.infer<typeof OrgView>;

export const UpdateProfileRequest = z.object({ displayName: z.string().trim().min(1).max(80) });
export const ChangeEmailRequest = z.object({ newEmail: Email, password: z.string().min(1).max(200) });

export const ContactTopic = z.enum(["sales", "support", "billing", "legal", "other"]);
export const ContactRequest = z.object({
  name: z.string().trim().min(1).max(80),
  email: Email,
  topic: ContactTopic,
  message: z.string().trim().min(10).max(5000),
  orgId: z.string().max(64).nullable().optional(),
});
export type ContactRequest = z.infer<typeof ContactRequest>;

export const InviteRequest = z.object({ email: Email, role: OrgRole.exclude(["owner"]) });

// ---------------------------------------------------------------------------- plans & billing

export const PlanFeatures = z.object({
  /** Automatic direction (the director owning the observer camera). */
  autoDirector: z.boolean(),
  /** Running exported models in shadow next to the baseline director. */
  learnedDirectorShadow: z.boolean(),
  /**
   * The Full Action Observer mode: nade (utility) cameras on top of POV observing and cinematics.
   * Observer and Observer & Cinematics are on every plan with autoDirector.
   */
  fullActionObserver: z.boolean().default(false),
  maxDevices: z.number().int().min(1),
  maxMembers: z.number().int().min(1),
});
export type PlanFeatures = z.infer<typeof PlanFeatures>;

export const Plan = z.object({
  id: z.string().regex(/^[a-z0-9-]{2,40}$/),
  name: z.string().min(1).max(60),
  description: z.string().max(500).default(""),
  /** Display price only; the charged price is the Stripe price referenced by stripePriceId. */
  priceMonthlyCents: z.number().int().min(0).nullable(),
  currency: z.string().length(3).default("usd"),
  includedAutoDirectorHours: z.number().min(0),
  features: PlanFeatures,
  stripePriceId: z.string().nullable(),
  public: z.boolean().default(true),
  sortOrder: z.number().int().default(0),
});
export type Plan = z.infer<typeof Plan>;

export const HourPack = z.object({
  id: z.string().regex(/^[a-z0-9-]{2,40}$/),
  name: z.string().min(1).max(60),
  hours: z.number().positive(),
  priceCents: z.number().int().min(0),
  currency: z.string().length(3).default("usd"),
  stripePriceId: z.string().nullable(),
  /** Credits expire this many days after purchase; null = never. */
  validDays: z.number().int().positive().nullable(),
  public: z.boolean().default(true),
});
export type HourPack = z.infer<typeof HourPack>;

export const SubscriptionStatus = z.enum(["none", "trialing", "active", "past_due", "canceled", "incomplete", "incomplete_expired", "unpaid", "paused"]);
export type SubscriptionStatus = z.infer<typeof SubscriptionStatus>;

export const CheckoutRequest = z.discriminatedUnion("kind", [
  z.object({ kind: z.literal("subscription"), planId: z.string() }),
  z.object({ kind: z.literal("hour_pack"), packId: z.string() }),
]);

// ---------------------------------------------------------------------------- device linking

/** Desktop → cloud: start linking (RFC 8628-style device authorization). */
export const DeviceAuthorizeRequest = z.object({
  deviceName: z.string().trim().min(1).max(80),
  platform: z.string().max(40),
  appVersion: z.string().max(40),
  /** Random per-install id generated by the desktop app (not a hardware fingerprint). */
  installId: z.string().regex(/^[A-Za-z0-9_-]{16,64}$/),
});
export type DeviceAuthorizeRequest = z.infer<typeof DeviceAuthorizeRequest>;

export const DeviceAuthorizeResponse = z.object({
  deviceCode: z.string(),
  userCode: z.string(),
  verificationUri: z.string(),
  verificationUriComplete: z.string(),
  expiresIn: z.number().int(),
  interval: z.number().int(),
});
export type DeviceAuthorizeResponse = z.infer<typeof DeviceAuthorizeResponse>;

export const DeviceTokenRequest = z.object({ deviceCode: z.string().min(16).max(128) });

export const DeviceTokenResponse = z.object({
  deviceId: z.string(),
  orgId: z.string(),
  orgName: z.string(),
  /** Long-lived device credential; send as Bearer to /v1/device/*. Store encrypted. */
  deviceToken: z.string(),
});
export type DeviceTokenResponse = z.infer<typeof DeviceTokenResponse>;

/** The account a computer is signed in as (the person who signed in, or who approved its link code). */
export const DeviceUser = z.object({ id: z.string(), email: z.string(), displayName: z.string() });
export type DeviceUser = z.infer<typeof DeviceUser>;

/** Sign in from the program with the website's email and password; returns a per-computer credential. */
export const DeviceLoginRequest = DeviceAuthorizeRequest.extend({
  email: Email,
  password: z.string().min(1).max(200),
  /** Required when the account belongs to more than one organisation (the server answers 409 choose_org with the list). */
  orgId: z.string().max(64).optional(),
});
export type DeviceLoginRequest = z.infer<typeof DeviceLoginRequest>;

export const DeviceLoginResponse = DeviceTokenResponse.extend({ user: DeviceUser });
export type DeviceLoginResponse = z.infer<typeof DeviceLoginResponse>;

/** detail of a 409 choose_org answer to /v1/device/login. */
export const DeviceLoginOrg = z.object({ id: z.string(), name: z.string(), role: OrgRole, planName: z.string() });
export type DeviceLoginOrg = z.infer<typeof DeviceLoginOrg>;

/** Errors returned while polling, as in RFC 8628. */
export const DeviceTokenError = z.enum(["authorization_pending", "slow_down", "expired_token", "access_denied"]);
export type DeviceTokenError = z.infer<typeof DeviceTokenError>;

export const DeviceApproveRequest = z.object({ userCode: z.string().trim().toUpperCase().regex(/^[A-Z]{4}-?[A-Z]{4}$/), orgId: z.string() });

// ---------------------------------------------------------------------------- entitlements

export const AutoDirectorAllowance = z.object({
  periodStart: z.string(),
  periodEnd: z.string(),
  includedSeconds: z.number().int().min(0),
  /** Unexpired purchased or granted hour credits. */
  creditSeconds: z.number().int().min(0),
  usedSeconds: z.number().int().min(0),
  remainingSeconds: z.number().int(),
  /** No surprise bills: false means automation cannot be re-armed once remainingSeconds ≤ 0. */
  overageAllowed: z.boolean(),
});
export type AutoDirectorAllowance = z.infer<typeof AutoDirectorAllowance>;

/** Signed by the cloud (Ed25519); the desktop verifies it offline with the pinned public key. */
export const EntitlementPayload = z.object({
  v: z.literal(1),
  iss: z.string(),
  kid: z.string(),
  orgId: z.string(),
  orgName: z.string(),
  deviceId: z.string(),
  plan: z.object({ id: z.string(), name: z.string() }),
  subscriptionStatus: SubscriptionStatus,
  features: PlanFeatures,
  autoDirector: AutoDirectorAllowance,
  issuedAt: z.string(),
  /** Refresh before this time. */
  expiresAt: z.string(),
  /** Offline grace: the desktop may keep using the entitlement until this time without reaching the cloud. */
  graceUntil: z.string(),
  /** Who this computer is signed in as (absent in licences from older servers). */
  user: DeviceUser.nullable().optional(),
});
export type EntitlementPayload = z.infer<typeof EntitlementPayload>;

// ---------------------------------------------------------------------------- usage

export const UsageRecord = z.object({
  /** Client-generated UUID; the server ignores repeats (idempotent uploads). */
  recordId: z.string().uuid(),
  kind: z.literal("auto_director"),
  startedAt: z.string().datetime(),
  endedAt: z.string().datetime(),
  seconds: z.number().int().min(1).max(6 * 3600),
  sessionId: z.string().max(80),
  matchRef: z.string().max(120).nullable().default(null),
  mapName: z.string().max(40).nullable().default(null),
  appVersion: z.string().max(40),
});
export type UsageRecord = z.infer<typeof UsageRecord>;

export const UsageBatch = z.object({ records: z.array(UsageRecord).min(1).max(500) });
export type UsageBatch = z.infer<typeof UsageBatch>;

export const UsageBatchResult = z.object({
  accepted: z.array(z.string()),
  duplicates: z.array(z.string()),
  rejected: z.array(z.object({ recordId: z.string(), reason: z.string() })),
});
export type UsageBatchResult = z.infer<typeof UsageBatchResult>;
